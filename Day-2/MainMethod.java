public class MainMethod 
{
    public static void main(String[] args) {
        System.out.println("public : The public access modifier is an access level modifier. It specifies that the member can be accessed from any other class.");
        System.out.println("static : The static keyword is used for memory management mainly. We can apply static keyword with variables, methods, blocks and nested class.");
        System.out.println("static : without creating an instance of the class, we can access the static method.");
        System.out.println("static : without creating an object of the class, we can access the static method.");
        System.out.println("non-static : create an object of the class and then we can access the non-static method.");
        System.out.println("void : The void keyword is used to specify that a method does not return any value.");
        System.out.println("main : The main method is the entry point of any Java program. It is the method that is called by the Java Virtual Machine (JVM) to start the execution of a Java program.");
        System.out.println("String[] args : The String[] args parameter is used to pass command-line arguments to the main method. It is an array of strings that can be used to pass information to the program when it is executed.");
        System.out.println("args : The args parameter is a variable name that can be used to refer to the array of strings passed to the main method. It can be any valid identifier, but args is commonly used as a convention.");
        
    }
    
}
