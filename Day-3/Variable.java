
class Variable
{
    public static void main(String[] args) 
    {
    
        System.out.println("DataType VariableName  = Value");
        int a = 10;
        System.out.println("int a = " + a);
        float b = 20.5f;
        System.out.println("float b = " + b);
        double c = 30.5;
        System.out.println("double c = " + c);
        boolean d = true;
        System.out.println("boolean d = " + d);
        char e = 'A';
        System.out.println("char e = " + e);
        String f = "Hello";
        System.out.println("String f = " + f);


        System.out.println();

        System.out.println("Types Of Variables : ");
        System.out.println("1. Local Variables");
        System.out.println("2. Instance Variables");
        System.out.println("3. Static Variables");

        
    }
}