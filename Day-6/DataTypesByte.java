class DataTypes
{
// Printing Default Value -->
// static --> static use Because Without Creating a Object Can Use it...
	static byte a;
	
	public static void main(String args[])
	{
		System.out.println("Byte DefaultValue : " + a);
		
		byte amount = 100;
		
		System.out.println("Amount : " + amount);
		
		byte max = 127;
		System.out.println("Maximum Value : " + max);
		
		byte min = -128;
		System.out.println("Minimum Value : " + min);
	
	}

}