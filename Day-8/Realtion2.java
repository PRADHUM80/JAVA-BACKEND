public class Realtion2 {

    public static void main(String[] args) {
        
        int a = Integer.parseInt(args[0]);
        int b = Integer.parseInt(args[1]);

        if(a == b)
        {
            System.out.println(a + " is equal to " + b);
        }
        else
        {
            System.out.println(a + " is not equal to " + b);
        }
    }
    
}
